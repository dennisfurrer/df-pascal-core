/// A 24 by 24 line icon drawn in the current text colour.
#[component]
pub fn Glyph(icon: Icon, #[prop(optional)] size: Option<u32>) -> impl IntoView {
    let size = size.unwrap_or(16);
    let svg = format!(
        r#"<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>"#,
        icon.body()
    );
    view! { <span class="glyph" inner_html=svg></span> }
}
